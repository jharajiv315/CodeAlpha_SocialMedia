import React, { useState } from 'react';
import { Modal } from '../../components/common/Modal';
import { Button } from '../../components/common/Button';
import { Input, TextArea } from '../../components/common/Input';
import { useAuth } from '../../hooks/useAuth';
import { dataService } from '../../services/dataService';
import { BuildStatus } from '../../types';
import { BUILD_CATEGORIES, BUILD_STATUS_CONFIG } from '../../config/constants';
import { sanitizeUrl } from '../../utils/security';
import { useRouter } from '../../hooks/useRouter';
import { showToast } from '../../hooks/useToast';

interface CreateBuildModalProps {
  isOpen: boolean;
  onClose: () => void;
  onBuildCreated?: (slug: string) => void;
}

export const CreateBuildModal: React.FC<CreateBuildModalProps> = ({
  isOpen,
  onClose,
  onBuildCreated
}) => {
  const { profile } = useAuth();
  const { navigate } = useRouter();

  const [title, setTitle] = useState('');
  const [summary, setSummary] = useState('');
  const [description, setDescription] = useState('');
  const [category, setCategory] = useState<string>(BUILD_CATEGORIES[0]);
  const [technologiesInput, setTechnologiesInput] = useState('');
  const [status, setStatus] = useState<BuildStatus>('IN_PROGRESS');
  const [githubUrl, setGithubUrl] = useState('');
  const [liveDemoUrl, setLiveDemoUrl] = useState('');
  const [documentationUrl, setDocumentationUrl] = useState('');
  const [isOpenCollab, setIsOpenCollab] = useState(false);
  const [rolesNeeded, setRolesNeeded] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!profile) return;
    setError('');

    if (!title.trim()) {
      setError('Please provide a project title');
      return;
    }
    if (!summary.trim()) {
      setError('Please provide a concise technical summary');
      return;
    }

    if (githubUrl.trim() && !sanitizeUrl(githubUrl)) {
      setError('Please enter a valid GitHub repository URL (e.g. https://github.com/org/repo)');
      return;
    }

    if (liveDemoUrl.trim() && !sanitizeUrl(liveDemoUrl)) {
      setError('Please enter a valid Live Demo URL (e.g. https://demo.example.com)');
      return;
    }

    if (documentationUrl.trim() && !sanitizeUrl(documentationUrl)) {
      setError('Please enter a valid Documentation URL (e.g. https://docs.example.com)');
      return;
    }

    setLoading(true);
    try {
      const technologies = technologiesInput
        .split(',')
        .map((t) => t.trim())
        .filter(Boolean);

      const created = await dataService.createBuild({
        ownerId: profile.id,
        title: title.trim(),
        slug: '', // generated by dataService
        summary: summary.trim(),
        description: description.trim() || summary.trim(),
        category,
        technologies: technologies.length > 0 ? technologies : ['TypeScript', 'Full-Stack'],
        status,
        visibility: 'PUBLIC',
        gallery: [],
        proof: {
          githubUrl: githubUrl.trim() || undefined,
          liveDemoUrl: liveDemoUrl.trim() || undefined,
          documentationUrl: documentationUrl.trim() || undefined
        },
        collabPosting: isOpenCollab
          ? {
              isOpen: true,
              rolesNeeded: rolesNeeded.split(',').map((r) => r.trim()).filter(Boolean),
              skillsRequired: technologies.slice(0, 3),
              estimatedDuration: '4 weeks',
              locationType: 'REMOTE',
              description: `Looking for collaborators to join ${title.trim()}`
            }
          : undefined
      });

      showToast(`Build "${created.title}" published!`, 'success');
      onClose();
      if (onBuildCreated) {
        onBuildCreated(created.slug);
      } else {
        navigate(`/builds/${created.slug}`);
      }
    } catch (err: any) {
      setError(err.message || 'Failed to create build');
    } finally {
      setLoading(false);
    }
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title="Start a New Build"
      subtitle="A Build is a living project object with persistent proof, milestones, and peer collaboration."
      maxWidth="620px"
    >
      <form onSubmit={handleSubmit} style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
        {error && (
          <div
            style={{
              padding: '8px 12px',
              backgroundColor: 'var(--danger-bg)',
              border: '1px solid var(--danger-border)',
              borderRadius: 'var(--radius-xs)',
              fontSize: '12.5px',
              color: 'var(--danger-text)'
            }}
          >
            {error}
          </div>
        )}

        {/* Title */}
        <Input
          label="Project Title"
          placeholder="e.g. ChronoCache or Nexora"
          value={title}
          onChange={(e) => setTitle(e.target.value)}
          required
        />

        {/* Category & Status */}
        <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '12px' }}>
          <div>
            <label style={{ fontSize: '12.5px', fontWeight: 500, color: 'var(--text-secondary)', display: 'block', marginBottom: '4px' }}>
              Category
            </label>
            <select
              value={category}
              onChange={(e) => setCategory(e.target.value)}
              className="input-base"
              style={{ padding: '8px 10px' }}
            >
              {BUILD_CATEGORIES.map((c) => (
                <option key={c} value={c}>
                  {c}
                </option>
              ))}
            </select>
          </div>

          <div>
            <label style={{ fontSize: '12.5px', fontWeight: 500, color: 'var(--text-secondary)', display: 'block', marginBottom: '4px' }}>
              Current Status
            </label>
            <select
              value={status}
              onChange={(e) => setStatus(e.target.value as BuildStatus)}
              className="input-base"
              style={{ padding: '8px 10px' }}
            >
              {(Object.keys(BUILD_STATUS_CONFIG) as BuildStatus[]).map((st) => (
                <option key={st} value={st}>
                  {BUILD_STATUS_CONFIG[st].label} - {BUILD_STATUS_CONFIG[st].description.slice(0, 30)}...
                </option>
              ))}
            </select>
          </div>
        </div>

        {/* Summary */}
        <Input
          label="Summary (One sentence technical essence)"
          placeholder="e.g. High-throughput LSM key-value store with io_uring and zero allocations."
          value={summary}
          onChange={(e) => setSummary(e.target.value)}
          required
        />

        {/* Full Description */}
        <TextArea
          label="Deep Dive & Architecture"
          placeholder="What problem does this project solve? What technical bottlenecks were eliminated? How does the data flow?"
          value={description}
          onChange={(e) => setDescription(e.target.value)}
          rows={4}
        />

        {/* Technologies */}
        <Input
          label="Tech Stack (Comma-separated)"
          placeholder="Rust, PostgreSQL, Docker, Linux, io_uring"
          value={technologiesInput}
          onChange={(e) => setTechnologiesInput(e.target.value)}
          hint="List libraries, databases, runtimes, and protocols used."
        />

        {/* Proof of Work */}
        <div style={{ paddingTop: '8px', borderTop: '1px solid var(--border-subtle)' }}>
          <div style={{ fontSize: '13px', fontWeight: 600, color: 'var(--text-primary)', marginBottom: '8px' }}>
            Proof of Work (Evidence)
          </div>
          <div style={{ display: 'flex', flexDirection: 'column', gap: '8px' }}>
            <Input
              placeholder="GitHub Repository URL (https://github.com/...)"
              value={githubUrl}
              onChange={(e) => setGithubUrl(e.target.value)}
            />
            <Input
              placeholder="Live Demo Deployment URL (https://...)"
              value={liveDemoUrl}
              onChange={(e) => setLiveDemoUrl(e.target.value)}
            />
            <Input
              placeholder="Documentation / Whitepaper URL (Optional)"
              value={documentationUrl}
              onChange={(e) => setDocumentationUrl(e.target.value)}
            />
          </div>
        </div>

        {/* Collaboration Call */}
        <div style={{ paddingTop: '8px', borderTop: '1px solid var(--border-subtle)' }}>
          <label style={{ display: 'flex', alignItems: 'center', gap: '8px', cursor: 'pointer' }}>
            <input
              type="checkbox"
              checked={isOpenCollab}
              onChange={(e) => setIsOpenCollab(e.target.checked)}
              style={{ accentColor: 'var(--accent-primary)' }}
            />
            <span style={{ fontSize: '13px', fontWeight: 500, color: 'var(--text-primary)' }}>
              Looking for collaborators on this build
            </span>
          </label>

          {isOpenCollab && (
            <div style={{ marginTop: '8px' }}>
              <Input
                label="Roles Needed (Comma-separated)"
                placeholder="Frontend Developer, Distributed Systems Engineer"
                value={rolesNeeded}
                onChange={(e) => setRolesNeeded(e.target.value)}
              />
            </div>
          )}
        </div>

        {/* Submit */}
        <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '8px', marginTop: '10px' }}>
          <Button variant="ghost" type="button" onClick={onClose}>
            Cancel
          </Button>
          <Button variant="primary" type="submit" loading={loading}>
            Publish Build
          </Button>
        </div>
      </form>
    </Modal>
  );
};
